import {execFileSync} from 'node:child_process';
import {expect,test} from '@playwright/test';

test('field team completes attendance, planned visit, DSR and follow-up with event-only GPS',async({page,context})=>{
  test.setTimeout(90_000);
  const account=execFileSync(process.execPath,['scripts/bootstrap-local.mjs','--disposable','--pilot-admin'],{
    encoding:'utf8',stdio:['ignore','pipe','pipe'],
  });
  const email=/^Email: (.+)$/m.exec(account)[1];
  const password=/^Password: (.+)$/m.exec(account)[1];
  const at='http://127.0.0.1:5173';
  const hospital='Synthetic Field Hospital';
  const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Kolkata'}).format(new Date());
  const tomorrow=new Date(Date.parse(today+'T00:00:00Z')+86_400_000).toISOString().slice(0,10);
  await context.grantPermissions(['geolocation'],{origin:at});
  await context.setGeolocation({latitude:19.076,longitude:72.8777,accuracy:16});
  await page.addInitScript(()=>{
    window.gpsRequests=0;
    const point=navigator.geolocation.getCurrentPosition.bind(navigator.geolocation);
    navigator.geolocation.getCurrentPosition=(...args)=>{window.gpsRequests++;return point(...args);};
    navigator.geolocation.watchPosition=()=>{throw new Error('Background GPS must not run');};
  });
  await page.goto('/attendance');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Attendance',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Start Working Day'}).click();
  let dialog=page.getByRole('dialog');
  await expect(dialog.getByRole('button',{name:'Start Working Day',exact:true})).toBeDisabled();
  expect(await page.evaluate(()=>window.gpsRequests)).toBe(0);
  await dialog.getByRole('button',{name:'Capture Location'}).click();
  await expect(dialog.getByRole('status')).toContainText('±16 m');
  expect(await page.evaluate(()=>window.gpsRequests)).toBe(1);
  await dialog.getByRole('button',{name:'Start Working Day',exact:true}).click();
  await page.getByRole('button',{name:'End Working Day',exact:true}).click();
  await dialog.getByLabel('Log Location Exception').check();
  await expect(dialog.getByRole('button',{name:'End Working Day',exact:true})).toBeDisabled();
  await dialog.getByLabel('Location exception reason').fill('Office GPS signal unavailable');
  await dialog.getByRole('button',{name:'End Working Day',exact:true}).click();
  await expect(page.getByText('Workday ended')).toBeVisible();
  await page.getByRole('button',{name:'Request Correction'}).click();
  await dialog.getByLabel('Requested status').selectOption('Work From Home');
  await dialog.getByLabel('Justification').fill('Worked remotely after the customer call');
  await dialog.getByRole('button',{name:'Request Correction',exact:true}).click();
  await page.getByRole('button',{name:'My Corrections'}).click();
  await expect(page.getByText('Worked remotely after the customer call')).toBeVisible();

  await page.goto('/customers');
  await page.getByRole('button',{name:'Add Customer',exact:true}).click();
  await dialog.getByLabel('Customer name',{exact:true}).fill(hospital);
  await dialog.getByRole('button',{name:'Save customer'}).click();
  await expect(page.getByRole('heading',{name:hospital,exact:true})).toBeVisible();
  await page.getByRole('button',{name:'+ Add Site',exact:true}).click();
  await dialog.getByLabel('Site name').fill('North campus');
  await dialog.getByLabel('Address',{exact:true}).fill('1 Synthetic Road');
  await dialog.getByLabel('Site latitude').fill('19.076');
  await dialog.getByLabel('Site longitude').fill('72.8777');
  await dialog.getByRole('button',{name:'Save site',exact:true}).click();
  await expect(dialog).toBeHidden();

  await page.goto('/visit-planner');
  await page.getByRole('button',{name:'Plan Visit',exact:true}).click();
  await dialog.getByLabel('Customer / Account').selectOption({label:hospital});
  await dialog.getByLabel('Site / Branch').selectOption({label:'North campus'});
  await dialog.getByLabel('Visit purpose').selectOption('Lead Follow-up');
  await dialog.getByRole('button',{name:'Plan Visit',exact:true}).click();
  await page.getByRole('button',{name:'Start Check-In →'}).click();
  await expect(page).toHaveURL(/\/field-visits\//);
  await expect(dialog).toBeVisible();
  expect(await page.evaluate(()=>window.gpsRequests)).toBe(0);
  await dialog.getByRole('button',{name:'Capture Location'}).click();
  await expect(dialog.getByRole('status')).toContainText('Verified On-Site');
  await dialog.getByRole('button',{name:'Check In to Visit',exact:true}).click();
  await page.getByRole('region',{name:'Active visit'}).getByRole('button',{name:'Check Out & Complete Report'}).click();
  await context.setGeolocation({latitude:19.1,longitude:72.9,accuracy:16});
  await dialog.getByRole('button',{name:'Capture Location'}).click();
  await expect(dialog.getByRole('status')).toContainText('Outside check-in radius');
  await dialog.getByLabel('Log Location Exception').check();
  await dialog.getByLabel('Location exception reason').fill('Meeting was at the off-site admin building');
  await dialog.getByLabel('Meeting outcome').selectOption('Quotation Requested');
  await dialog.getByLabel('Next action',{exact:true}).fill('Send equipment specification');
  await dialog.getByLabel('Next follow-up date and time (IST)').fill(tomorrow+'T10:00');
  await dialog.getByLabel('Create New Lead from Visit').check();
  await dialog.getByRole('button',{name:'Check Out & Complete Report',exact:true}).click();
  await expect(page.getByText('Visit report saved.')).toBeVisible();
  await page.getByRole('button',{name:'Daily Sales Reports (DSR)',exact:true}).click();
  const report=page.getByRole('region',{name:'Daily Sales Report'});
  await expect(report).toContainText('1 of 1');
  await expect(report).toContainText(hospital);
  await expect(report.getByText('Visits with location exceptions').locator('..')).toContainText('1');
  await page.goto('/customers');
  await page.getByRole('button',{name:hospital,exact:true}).click();
  await expect(page.getByRole('region',{name:'Upcoming Tasks'})).toContainText('Send equipment specification');
  await page.getByRole('button',{name:'Field Visits',exact:true}).last().click();
  await expect(page.getByRole('region',{name:'Visit History'})).toContainText('Quotation Requested');
  await page.goto('/tasks');
  const shell=page.locator('.sales-shell');
  if(await shell.getAttribute('data-theme')==='light'){
    await page.getByRole('button',{name:'Switch to dark mode'}).click();
  }
  await expect(shell).toHaveAttribute('data-theme','dark');
  await page.getByRole('button',{name:'Upcoming Tasks',exact:true}).click();
  const followup=page.getByRole('listitem').filter({hasText:'Send equipment specification'});
  await expect(followup).toHaveCount(1);
  await followup.getByRole('button',{name:'Reschedule',exact:true}).click();
  await dialog.locator('input[name="starts_at"]').fill(tomorrow+'T11:00');
  await dialog.getByLabel('Reschedule reason').fill('Customer is available one hour later');
  await dialog.getByRole('button',{name:'Reschedule',exact:true}).click();
  await followup.getByText('Task history').click();
  await expect(followup).toContainText('Customer is available one hour later');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
});
